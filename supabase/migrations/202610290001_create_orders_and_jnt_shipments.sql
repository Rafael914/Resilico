-- Ordering foundation for Resilico. Inventory is stored per product variant.
-- Run this migration in the shared Supabase project.

create table if not exists public.orders (
  order_id bigint generated by default as identity primary key,
  user_id integer not null references public.users(user_id) on delete restrict,
  status text not null default 'pending',
  total_amount numeric(10,2) not null check (total_amount >= 0),
  shipping_address_id integer references public.address(address_id) on delete restrict,
  shipping_name text not null,
  shipping_phone text not null,
  shipping_address_line1 text not null,
  shipping_address_line2 text,
  shipping_city text not null,
  shipping_province text not null,
  shipping_postal_code text not null,
  shipping_country text not null default 'Philippines',
  created_at timestamptz not null default now()
);

-- Existing projects may already have an orders table with a smaller column set.
-- Add the columns required by checkout without disturbing existing order records.
alter table public.orders
  add column if not exists user_id integer references public.users(user_id) on delete restrict,
  add column if not exists status text default 'Pending',
  add column if not exists total_amount numeric(10,2) default 0,
  add column if not exists shipping_address_id integer references public.address(address_id) on delete restrict,
  add column if not exists shipping_name text,
  add column if not exists shipping_phone text,
  add column if not exists shipping_address_line1 text,
  add column if not exists shipping_address_line2 text,
  add column if not exists shipping_city text,
  add column if not exists shipping_province text,
  add column if not exists shipping_postal_code text,
  add column if not exists shipping_country text default 'Philippines',
  add column if not exists created_at timestamptz default now();

alter table public.orders
  drop constraint if exists orders_status_check;

update public.orders
set status = lower(status)
where status is not null and status <> lower(status);

update public.orders
set status = 'pending'
where status is null or trim(status) = '';

alter table public.orders
  alter column status set default 'pending',
  alter column status set not null,
  add constraint orders_status_check check (length(trim(status)) > 0);

create table if not exists public.order_items (
  order_item_id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(order_id) on delete restrict,
  product_id integer not null references public.products(product_id) on delete restrict,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0)
);

alter table public.order_items
  add column if not exists order_id bigint references public.orders(order_id) on delete restrict,
  add column if not exists product_id integer references public.products(product_id) on delete restrict,
  add column if not exists variant_id integer references public.product_variant(variant_id) on delete restrict,
  add column if not exists product_name text,
  add column if not exists quantity integer,
  add column if not exists unit_price numeric(10,2);

create table if not exists public.shipments (
  shipment_id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.orders(order_id) on delete restrict,
  carrier text not null default 'J&T Express',
  tracking_number text unique,
  shipping_status text not null default 'Preparing'
    check (shipping_status in ('Preparing', 'In Transit', 'Delivered', 'Returned')),
  shipped_at timestamptz,
  estimated_delivery timestamptz,
  created_at timestamptz not null default now()
);

-- Existing projects may have an older constraint that rejects the admin's
-- shipment statuses. Normalize legacy values, then align it with the app.
alter table public.shipments
  drop constraint if exists shipments_shipping_status_check;

update public.shipments
set shipping_status = case lower(trim(coalesce(shipping_status, '')))
  when 'preparing' then 'Preparing'
  when 'pending' then 'Preparing'
  when 'in transit' then 'In Transit'
  when 'shipped' then 'In Transit'
  when 'delivered' then 'Delivered'
  when 'returned' then 'Returned'
  else 'Preparing'
end
where shipping_status is null
   or shipping_status not in ('Preparing', 'In Transit', 'Delivered', 'Returned');

alter table public.shipments
  alter column shipping_status set default 'Preparing',
  add constraint shipments_shipping_status_check
    check (shipping_status in ('Preparing', 'In Transit', 'Delivered', 'Returned'));

create index if not exists orders_user_created_idx on public.orders(user_id, created_at desc);
create index if not exists order_items_order_idx on public.order_items(order_id);

grant select, insert, update, delete on table public.products, public.product_variant to service_role;
grant select, insert, update, delete on table public.users to service_role;
grant select, insert, update, delete on table public.address to service_role;
grant select, insert, update, delete on table public.orders, public.order_items, public.shipments to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function public.place_resilico_order(
  p_user_id integer,
  p_items jsonb,
  p_shipping jsonb
) returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_id bigint;
  v_item jsonb;
  v_product public.products%rowtype;
  v_variant public.product_variant%rowtype;
  v_address_id public.address.address_id%type;
  v_quantity integer;
  v_total numeric(10,2) := 0;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Order must contain at least one item.' using errcode = '22023';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if coalesce((v_item->>'productId')::integer, 0) < 1
       or coalesce((v_item->>'quantity')::integer, 0) < 1 then
      raise exception 'Each item needs a valid productId and positive quantity.' using errcode = '22023';
    end if;
    v_quantity := (v_item->>'quantity')::integer;
    select * into v_product from public.products
      where product_id = (v_item->>'productId')::integer and is_active = true
      for update;
    if not found then
      raise exception 'A product is unavailable.' using errcode = 'P0002';
    end if;
    select * into v_variant from public.product_variant
      where product_id = v_product.product_id and stock_quantity >= v_quantity
      order by variant_id limit 1 for update;
    if not found then
      raise exception 'Insufficient stock for %.', v_product.name using errcode = '22023';
    end if;
    v_total := v_total + v_product.base_price * v_quantity;
  end loop;

  insert into public.address (
    user_id, address_line1, address_line2, country, province_state, city, postal_code
  ) values (
    p_user_id, p_shipping->>'addressLine1', nullif(p_shipping->>'addressLine2', ''),
    coalesce(nullif(p_shipping->>'country', ''), 'Philippines'), p_shipping->>'province',
    p_shipping->>'city', p_shipping->>'postalCode'
  ) returning address_id into v_address_id;

  insert into public.orders (
    user_id, total_amount, shipping_address_id, shipping_name, shipping_phone,
    shipping_address_line1, shipping_address_line2, shipping_city,
    shipping_province, shipping_postal_code, shipping_country
  ) values (
    p_user_id, v_total, v_address_id, p_shipping->>'name', p_shipping->>'phone',
    p_shipping->>'addressLine1', nullif(p_shipping->>'addressLine2', ''),
    p_shipping->>'city', p_shipping->>'province', p_shipping->>'postalCode',
    coalesce(nullif(p_shipping->>'country', ''), 'Philippines')
  ) returning order_id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_quantity := (v_item->>'quantity')::integer;
    select * into v_product from public.products
      where product_id = (v_item->>'productId')::integer for update;
    select * into v_variant from public.product_variant
      where product_id = v_product.product_id and stock_quantity >= v_quantity
      order by variant_id limit 1 for update;
    update public.product_variant set stock_quantity = stock_quantity - v_quantity
      where variant_id = v_variant.variant_id;
    insert into public.order_items (order_id, product_id, variant_id, product_name, quantity, unit_price)
      values (v_order_id, v_product.product_id, v_variant.variant_id, v_product.name, v_quantity, v_product.base_price);
  end loop;

  insert into public.shipments (order_id, carrier) values (v_order_id, 'J&T Express');
  return v_order_id;
end;
$$;

revoke all on function public.place_resilico_order(integer, jsonb, jsonb) from public, anon, authenticated;
grant execute on function public.place_resilico_order(integer, jsonb, jsonb) to service_role;

